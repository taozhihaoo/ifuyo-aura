#!/usr/bin/env node
// 从 brand.json（品牌唯一事实来源）生成 ui/src/generated/tokens.css，
// 并校验 ui/src/design/tokens.ts 的 colors 与 brand.json 一致。
// 用法：node scripts/generate-tokens.mjs（或 ui/ 下 npm run tokens）
// 零依赖：仅使用 Node 内置模块。

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brand = JSON.parse(readFileSync(join(root, 'brand.json'), 'utf8'));
const tokensPath = join(root, 'ui', 'src', 'design', 'tokens.ts');
const outPath = join(root, 'ui', 'src', 'generated', 'tokens.css');

const brandColors = brand.colors;
if (!brandColors || typeof brandColors !== 'object') {
  console.error('brand.json 缺少 colors');
  process.exit(1);
}

// 1) 校验 tokens.ts 与 brand.json 颜色一致（防两套事实）
const tokensSrc = readFileSync(tokensPath, 'utf8');
for (const [key, value] of Object.entries(brandColors)) {
  const re = new RegExp(`(?<![\\w-])${key}:\\s*'${value}'`);
  if (!re.test(tokensSrc)) {
    console.error(
      `不一致：tokens.ts 中 ${key} 不等于 brand.json 的 ${value}。` +
        `请以 brand.json 为准更新 ui/src/design/tokens.ts。`,
    );
    process.exit(1);
  }
}

// 2) 解析 tokens.ts 的全部 token 组（colors 之外的组同样以 tokens.ts 为事实来源）
function parseGroups(src) {
  const groups = {};
  const blockRe = /export const (\w+) = \{([\s\S]*?)\}/g;
  for (const [, name, body] of src.matchAll(blockRe)) {
    const entries = {};
    for (const [, key, value] of body.matchAll(/(?<![\w-])(\w+):\s*'([^']*)'/g)) entries[key] = value;
    groups[name] = entries;
  }
  return groups;
}

const groups = parseGroups(tokensSrc);

// CSS variable 名 → token 组.键：app.css 消费的是这一套命名，两侧不得各自演化。
const cssVars = [
  ['--surface-low', 'surface.low'],
  ['--surface-high', 'surface.high'],
  ['--surface-border', 'surface.border'],
  ['--color-text', 'text.primary'],
  ['--color-text-muted', 'text.secondary'],
  ['--radius-sm', 'radius.sm'],
  ['--radius-md', 'radius.md'],
  ['--font-size-xs', 'typeScale.xs'],
  ['--font-size-sm', 'typeScale.sm'],
  ['--font-size-md', 'typeScale.md'],
  ['--font-size-lg', 'typeScale.lg'],
  ['--font-size-xl', 'typeScale.xl'],
  ['--motion-fast', 'motion.fast'],
  ['--motion-normal', 'motion.base'],
  ['--motion-slow', 'motion.slow'],
  ['--ease-out', 'ease.out'],
];

const lines = Object.entries(brandColors).map(([k, v]) => `  --color-${k}: ${v};`);
for (const [varName, path] of cssVars) {
  const [group, key] = path.split('.');
  const value = groups[group]?.[key];
  if (value === undefined) {
    console.error(`tokens.ts 缺少 ${path}（${varName} 无法生成）——请补齐或改名。`);
    process.exit(1);
  }
  lines.push(`  ${varName}: ${value};`);
}

const css = [
  '/* Auto-generated by scripts/generate-tokens.mjs from brand.json + design/tokens.ts — DO NOT EDIT. */',
  '/* Run `npm run tokens` (in ui/) to regenerate. */',
  ':root {',
  ...lines,
  '}',
  '',
].join('\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, css);
console.log(`written: ${outPath}`);
